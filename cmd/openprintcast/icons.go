// Apple system colors for the icon tiles, as in System Settings rows: a
// white glyph on a rounded colored square.
var (
	tileGray   = ui.RGB(142, 142, 147)
	tileOrange = ui.RGB(255, 159, 10)
)

const tileSize = 30

func iconTile(c *ui.Context, icon *ui.SVG, bg ui.Color) { iconTileSized(c, icon, bg, tileSize) }

func iconTileSized(c *ui.Context, icon *ui.SVG, bg ui.Color, size float32) {
	ui.Box(c).Size(size, size).Shrink(0).Radius(size / 4).Background(bg).Center().Children(func() {
		ui.Icon(c, icon).FontSize(size * 0.6).TextColor(ui.RGB(255, 255, 255))
	})
}

// jobStatusIcon gives each job state its own shape, so status reads
// without color.
func jobStatusIcon(s core.JobStatus) *ui.SVG {
	switch s {
	case core.JobCompleted:
		return checkCircleIcon
	case core.JobFailed:
		return crossCircleIcon
	case core.JobCancelled:
		return banIcon
	case core.JobPrinting:
		return printerIcon
	default:
		return clockIcon
	}
}

// conditionSymbol gives each printer condition its own shape.
func conditionSymbol(k conditionIcon) *ui.SVG {
	switch k {
	case conditionIconReady:
		return checkCircleIcon
	case conditionIconPrinting:
		return printerIcon
	case conditionIconPaused:
		return pauseIcon
	case conditionIconAlert:
		return alertIcon
	default:
		return helpIcon
	}
}
